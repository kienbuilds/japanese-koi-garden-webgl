import { chromium } from 'playwright';
const b = await chromium.launch({ channel: 'chrome', args: ['--use-angle=d3d11', '--enable-gpu', '--ignore-gpu-blocklist'] });
const p = await b.newPage({ viewport: { width: 1600, height: 900 } });
const errs = []; p.on('pageerror', (e) => errs.push(e.message)); p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await p.goto('http://localhost:5173/');
await p.waitForFunction(() => window.__koiReady === true, null, { timeout: 180000 });
await p.waitForTimeout(1200);
await p.screenshot({ path: 'screenshots/hint_1.png', clip: { x: 1180, y: 780, width: 420, height: 120 } });
const vis = () => p.evaluate(() => ({ hint: getComputedStyle(document.getElementById('hint')).display, gui: getComputedStyle(document.querySelector('.lil-gui.lil-root')).display }));
console.log('start ', JSON.stringify(await vis()));
await p.click('#hint');
await p.waitForTimeout(400);
console.log('click ', JSON.stringify(await vis()));
await p.screenshot({ path: 'screenshots/hint_2.png' });
await p.click('.lil-gui.lil-root > .lil-title span');
await p.waitForTimeout(300);
console.log('close ', JSON.stringify(await vis()));
await p.keyboard.press('g'); await p.waitForTimeout(300);
console.log('key g ', JSON.stringify(await vis()));
await p.keyboard.press('g'); await p.waitForTimeout(300);
console.log('key g2', JSON.stringify(await vis()));
await p.waitForTimeout(6500);
console.log('dim after 6s:', await p.evaluate(() => document.getElementById('hint').classList.contains('dim')));
console.log('errors:', errs.length ? errs.join(' | ') : 'none');
await b.close();
